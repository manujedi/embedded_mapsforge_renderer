const theme *get_theme(char *tag) {
  // exact match?
  for (size_t i = 0; i < sizeof(table) / sizeof(table[0]); i++) {
    if (strcmp(tag, table[i].name) == 0) {
      return &table[i];
    }
  }

  // wildcard?
  for (size_t i = 0; i < sizeof(table) / sizeof(table[0]); i++) {
    bool wildcard = false;
    uint32_t wildcard_prefix = 0;
    for (size_t j = 0; j < strlen(table[i].name); j++) {
      if (table[i].name[j] == '*') {
        wildcard_prefix = j;
        wildcard = true;
        break;
      }
    }

    if (wildcard) {
      if (memcmp(table[i].name, tag, wildcard_prefix) == 0) {
        return &table[i];
      }
    }
  }

  return NULL;
}
